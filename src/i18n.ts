export function detectLocale(joplinLocale: string): string {
  const l = String(joplinLocale || '').toLowerCase();
  for (const pre of ['ru', 'de', 'es', 'pt', 'fr', 'sr', 'zh', 'ja']) {
    if (l.startsWith(pre)) return pre;
  }
  return 'en';
}

export function buildDict(locale: string, custom: Record<string, Record<string, string>>): Record<string, string> {
  return Object.assign({}, BUILTIN.en, (BUILTIN[locale] || {}), (custom && custom[locale]) || {});
}